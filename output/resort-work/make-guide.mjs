import fs from 'node:fs';
import ts from '../../node_modules/typescript/lib/typescript.js';
import { createRequire } from 'node:module'; const require = createRequire('/Users/trckwrk/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/package.json'); const sharp = require('sharp');
const source = fs.readFileSync('src/render/dollArt.ts', 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText;
const { OUTLINES, HEAD } = await import('data:text/javascript;base64,' + Buffer.from(js).toString('base64'));
const names = ['Head','Tors','Ass','ArmLeft','ArmRight','HandLeft','HandRight','FingerLeft','FingerRight','LegLeft','LegRight','FootLeft','FootRight'];
let svg = '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024"><rect width="1024" height="1024" fill="#eef0f1"/>';
const meta={};
names.forEach((name,i)=>{
 const pts=OUTLINES[name];
 const xs=pts?.filter((_,i)=>i%2===0), ys=pts?.filter((_,i)=>i%2===1);
 const x=pts?Math.min(...xs):HEAD.cx-HEAD.rx, y=pts?Math.min(...ys):HEAD.cy-HEAD.ry;
 const w=(pts?Math.max(...xs):HEAD.cx+HEAD.rx)-x, h=(pts?Math.max(...ys):HEAD.cy+HEAD.ry)-y;
 const scale=210/Math.max(w,h), cx=(i%4)*256+128, cy=Math.floor(i/4)*256+128;
 const dx=cx-(x+w/2)*scale, dy=cy-(y+h/2)*scale;
 meta[name]={col:i%4,row:Math.floor(i/4),x:(i%4*256-dx)/scale,y:(Math.floor(i/4)*256-dy)/scale,w:256/scale,h:256/scale};
 svg += `<g transform="translate(${dx} ${dy}) scale(${scale})" fill="${name==='Ass'?'#169596':'#dba277'}">`;
 if(pts) svg+=`<polygon points="${pts.join(' ')}"/>`;
 else svg+=`<ellipse cx="${HEAD.cx}" cy="${HEAD.cy}" rx="${HEAD.rx}" ry="${HEAD.ry}"/>`;
 svg+='</g>';
});
svg+='</svg>';
fs.writeFileSync('output/resort-work/guide.svg',svg);
fs.writeFileSync('output/resort-work/atlas-layout.json',JSON.stringify(meta,null,2));
await sharp(Buffer.from(svg)).png().toFile('output/resort-work/guide.png');

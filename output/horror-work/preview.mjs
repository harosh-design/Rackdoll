import fs from 'node:fs/promises';
import { createRequire } from 'node:module';
const { chromium } = createRequire('/Users/trckwrk/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/package.json')('playwright');
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', event => { if (event.type() === 'error' || event.type() === 'warning') errors.push(event.text()); });
try {
  await page.goto('http://127.0.0.1:5173/');
  await page.waitForFunction(() => window.__rv);
  await page.evaluate(() => window.__rv.renderer.ready);
  await page.locator('[data-mode="2p"]').click();
  await page.locator('#play').click();
  await page.waitForTimeout(1000);
  await page.keyboard.press('p');
  await page.locator('#pause').evaluate(element => { element.style.visibility = 'hidden'; });
  await page.locator('#game').screenshot({ path: 'output/horror-work/game-standing.png' });
  await page.screenshot({ path: 'output/horror-work/page.png' });
  const audit = await page.evaluate(async () => {
    const { drawHorrorPlayers, loadHorrorArt } = await import('/src/render/horrorArt.ts');
    const { closedPoses } = await import('/src/render/dollPose.ts');
    const { GameWorld } = await import('/src/sim/world.ts');
    await loadHorrorArt();
    const world = new GameWorld({ singlePlayer: false, hazards: false });
    const poses = { pose(body) { const p = body.getPosition(); return { x: p.x * 30, y: p.y * 30, a: body.getAngle() }; } };
    const frame = closedPoses(poses, 1, [world.p1, world.p2], world.ball.body);
    const canvas = document.createElement('canvas'); canvas.width = 1200; canvas.height = 480;
    const ctx = canvas.getContext('2d'); ctx.fillStyle = '#496ba9'; ctx.fillRect(0, 0, 1200, 480);
    ctx.setTransform(3, 0, 0, 3, 0, -675);
    drawHorrorPlayers(ctx, [world.p1], frame, 1);
    ctx.setTransform(3, 0, 0, 3, -660, -675);
    drawHorrorPlayers(ctx, [world.p2], frame, 1);
    return { poses: canvas.toDataURL('image/png'), settings: window.__rv.settings, resources: performance.getEntriesByType('resource').map(entry => entry.name).filter(name => name.includes('/art/')) };
  });
  await fs.writeFile('output/horror-work/player-poses.png', Buffer.from(audit.poses.split(',')[1], 'base64'));
  delete audit.poses;
  await fs.writeFile('output/horror-work/preview-audit.json', JSON.stringify({ ...audit, errors }, null, 2));
  console.log(JSON.stringify({ errors, resources: audit.resources }, null, 2));
} finally { await browser.close(); }
